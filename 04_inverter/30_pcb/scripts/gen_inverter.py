"""Generates the three-phase inverter KiCad project (schematic + PCB) in 04_inverter/30_pcb/inverter/.

    python gen_inverter.py            # schematic + PCB pipeline (place, route, silk, DRC)
    python gen_inverter.py --sch      # schematic only

Design values: 04_inverter/10_math/01_ideal.md and 02_losses.md. Gate bus: 00_docs/gate_bus_interface.md.
Channel map: PWM1 -> Q1 (A high), PWM2 -> Q4 (A low), PWM3 -> Q3 (B high), PWM4 -> Q6 (B low),
             PWM5 -> Q5 (C high), PWM6 -> Q2 (C low).
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "90_tools", "kicad_blocks"))
import pe_blocks as pe                                   # noqa: E402
from kicad_sch_gen import Design                         # noqa: E402

OUT = os.path.join(HERE, "..", "inverter")
PROJECT = "inverter"
FP = pe.FP

# driver channel n -> (switch ref, collector net, emitter net, high side?)
LEGS = {1: ("Q1", "VDC", "A", True), 2: ("Q4", "A", "COM", False),
        3: ("Q3", "VDC", "B", True), 4: ("Q6", "B", "COM", False),
        5: ("Q5", "VDC", "C", True), 6: ("Q2", "C", "COM", False)}


def build():
    d = Design(PROJECT, power_nets=("+12V", "GND"),
               title_block=dict(company="UPB - Power Electronics", rev="0.1",
                                comments=["Three-phase inverter box, 60-320 V DC link, 300 W, six IGBTs"]))
    sh = d.root("A2", title="Three-phase inverter (six-switch bridge, external gating block)")

    # --- Gate bus and the six driver cells (high side: own TMA; low side: shared VCC_LS from the protection cell)
    pe.gate_bus(sh, 20, 30, used=(1, 2, 3, 4, 5, 6), ref="J1")
    for n, (q, c, e, high) in LEGS.items():
        col, row = (n - 1) % 2, (n - 1) // 2
        pe.driver_cell(sh, n, 90 + 85 * col, 30 + 42 * row, f"PWM{n}", f"G{n}", e, supply=high,
                       vcc=None if high else "VCC_LS", title=f"Gate driver {n}: PWM{n} -> {q} ({'high' if high else 'low'} side, {c}-{e})")
    pe.protection_cell(sh, 20, 170, "VCC_LS", "VDC", "6k2", i_trip_label="4 A", ov_label="(V_DC > 380 V)",
                       with_supply=True)

    # --- Power stage
    sh.rect(270, 30, 500, 170, "Power stage: DC link 60-320 V, three legs, outputs A B C")
    sh.part("Connector:Screw_Terminal_01x02", "J2", "DC IN", 280, 60, {"1": "VDC+", "2": "GND_P"}, fp=FP["TB2"])
    sh.two("Device:Fuse", "F1", "4A T", 295, 46, "VDC+", "VF", fp=FP["FUSE"])
    sh.two("Device:Thermistor_NTC", "TH1", "NTC 10R", 310, 46, "VF", "VDC", fp=FP["NTC"])
    pe.dc_bus_caps(sh, 320, 60, "VDC", "COM", pe.Refs("C", 1), n_elec=2, title="DC link 2 x 47u/450V + 4.7u film")
    for n, (q, c, e, high) in LEGS.items():
        x = 360 + 40 * ((n - 1) // 2)
        y = 50 if high else 90
        sh.part("Device:Q_NIGBT_GCE", q, "IRG4PC40UD", x, y, {"1": f"G{n}", "2": c, "3": e}, fp=FP["TO247"])
    sh.part("Connector:Screw_Terminal_01x03", "J3", "AC OUT", 480, 70, {"1": "A", "2": "B", "3": "C"}, fp=FP["TB3"])
    pe.bleeder_led(sh, 320, 110, "VDC", "COM", pe.Refs("R", 1), "D2", title="Bleeder / DC link charged")
    for k, net in enumerate(["VDC", "A", "B", "C", "COM", "GND_P"]):
        pe.test_point(sh, f"TP{k+1}", net, 290 + 20 * k, 150)
    pe.mounting_holes(sh, 420, 150)
    sh.text("Shunt R90 (0.1 ohm) between COM (low-side emitters) and GND_P (V_DC- terminal): TP5-TP6 = 0.1 V/A of "
            "DC-link current. Dead time (>= 1.5 us) is generated by the gating block; there is no hardware interlock.",
            20, 240, size=1.5, bold=False)

    pro_tpl = pe.pro_template(os.path.join(HERE, "pro_template.json"))
    patterns = {"/VDC+": "Power", "/VF": "Power", "/VDC": "Power", "/A": "Power", "/B": "Power", "/C": "Power",
                "/COM": "Power", "/GND_P": "Power", "/G?": "HV_signal", "/VO?": "HV_signal", "/VCC?": "HV_signal",
                "/VCC_LS": "HV_signal", "/VDC_BL*": "HV_signal", "/OVMID": "HV_signal", "/ISENSE": "Aux",
                "/IREF*": "Aux", "/OVSENSE": "Aux", "/VREF": "Aux", "/FLT*": "Aux"}
    d.write(OUT, template_pro=pro_tpl, netclasses=pe.POWER_CLASSES, patterns=patterns, rules=pe.RULES)
    os.remove(pro_tpl)
    print("schematic written to", os.path.normpath(OUT))


if __name__ == "__main__":
    build()
    if "--sch" not in sys.argv:
        rc = subprocess.run([sys.executable, os.path.join(pe.SKILL, "pcb_pipeline.py"),
                             os.path.join(OUT, PROJECT + ".kicad_pro"), os.path.join(HERE, "pcb_config.json")]
                            + [a for a in sys.argv[1:] if a.startswith("--")]).returncode
        sys.exit(rc)
